import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { randomBytes } from "node:crypto";
import pg from "pg";
const status = JSON.parse(readFileSync(".local/supabase-status.json", "utf8"));
if (!["localhost", "127.0.0.1"].includes(new URL(status.API_URL).hostname))
  throw new Error("This setup is restricted to local Supabase.");
const admin = createClient(status.API_URL, status.SERVICE_ROLE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});
const config = JSON.parse(readFileSync(".local/database.json", "utf8"));
const db = new pg.Client({ connectionString: config.ownerUrl });
await db.connect();
const password = existsSync(".local/reviewer-accounts.json")
  ? JSON.parse(readFileSync(".local/reviewer-accounts.json", "utf8")).password
  : `Demo-${randomBytes(12).toString("base64url")}!`;
const accounts = [
  {
    email: "guest.a@resort.example",
    name: "Synthetic Guest A",
    role: "guest",
    gm: false,
  },
  {
    email: "guest.b@resort.example",
    name: "Synthetic Guest B",
    role: "guest",
    gm: false,
  },
  {
    email: "reservations@resort.example",
    name: "Synthetic Reservations",
    role: "staff",
    gm: false,
  },
  { email: "gm@resort.example", name: "Synthetic GM", role: "staff", gm: true },
];
try {
  const { data: existing, error: listingError } =
    await admin.auth.admin.listUsers();
  if (listingError) throw new Error("Could not list local synthetic users.");
  for (const account of accounts) {
    const found = existing.users.find((u) => u.email === account.email);
    const result = found
      ? await admin.auth.admin.updateUserById(found.id, {
          password,
          email_confirm: true,
        })
      : await admin.auth.admin.createUser({
          email: account.email,
          password,
          email_confirm: true,
          user_metadata: { display_name: account.name },
        });
    if (result.error || !result.data.user)
      throw new Error(`Could not prepare synthetic account ${account.email}.`);
    account.id = result.data.user.id;
    await db.query(
      "insert into resort.profiles(id,display_name,role,is_gm) values($1,$2,$3,$4) on conflict(id) do update set display_name=excluded.display_name,role=excluded.role,is_gm=excluded.is_gm",
      [account.id, account.name, account.role, account.gm],
    );
  }
} finally {
  await db.end();
}
const file = ".env.local";
let env = readFileSync(file, "utf8");
for (const [name, value] of Object.entries({
  NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY:
    status.PUBLISHABLE_KEY || status.ANON_KEY,
})) {
  env =
    env
      .split("\n")
      .filter((line) => !line.startsWith(`${name}=`))
      .join("\n")
      .trimEnd() + `\n${name}=${value}\n`;
}
writeFileSync(file, env, { mode: 0o600 });
writeFileSync(
  ".local/reviewer-accounts.json",
  JSON.stringify({ accounts, password }, null, 2),
  { mode: 0o600 },
);
writeFileSync(
  ".local/reviewer-accounts.md",
  `# Local synthetic reviewer accounts\n\nOnly for this local assessment. No real systems or data. Regenerated by setup-auth.mjs.\n\n${accounts.map((a) => `- ${a.email} — ${a.role}${a.gm ? " with GM permission" : ""}`).join("\n")}\n\nPassword for these deliberately created local accounts: ${password}\n`,
  { mode: 0o600 },
);
console.log(
  "Local Supabase Auth configured; four synthetic accounts created. Credentials are in ignored .local/reviewer-accounts.md and were not printed.",
);
